const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const ctx={URL};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync(path.resolve(__dirname,"../archive-scope.js"),"utf8"),ctx);
const api=ctx.RarRescueArchiveScope;
const link="https://disk.yandex.ru/d/_RSlWomRWmty1w";
const missing=api.resolveName(link,[
  {source:"viewer",value:null},{source:"page",value:"Яндекс Диск"}]);
assert.equal(missing.fallback,true);
assert.equal(missing.archiveName,"Yandex-RAR-_RSlWomRWmty1w.rar");
assert.equal(missing.viewerExpectedTitle,null);
assert.equal(api.fromYandexPublicLink(link,missing.archiveName).archiveName,missing.archiveName);
const title=api.resolveName(link,[{source:"page",value:"Диск 2.rar — Яндекс Диск"}]);
assert.equal(title.archiveName,"Диск 2.rar");
assert.equal(title.fallback,false);
assert.equal(title.viewerExpectedTitle,null);
const viewer=api.resolveName(link,[{source:"viewer",value:"«Диск 2.rar»"}]);
assert.equal(viewer.archiveName,"Диск 2.rar");
assert.equal(viewer.viewerExpectedTitle,"«Диск 2.rar»");
const invalid=api.resolveName(link,[{source:"viewer",value:"CON.rar"},{source:"page",value:"Архив:Нельзя.rar"}]);
assert.equal(invalid.fallback,true);
assert.equal(api.resolveName(link,[{source:"page",value:"../../evil.rar"}]).fallback,true);
assert.equal(api.resolveName(link+"?secret=NEVER_LOG#fragment",[]).archiveName,missing.archiveName);
const long=api.resolveName("https://disk.yandex.ru/d/"+"x".repeat(150),[]);
assert(long.archiveName.length<=120);
assert.equal(api.archiveName(long.archiveName),long.archiveName);
assert.notEqual(api.resolveName("https://disk.yandex.ru/d/other",[]).archiveName,missing.archiveName);
assert.throws(()=>api.resolveName("https://evil.example.com/d/other",[]));
console.log("PASS: generic Yandex page-title fallback, verified viewer name, safe distinct Windows folder");
