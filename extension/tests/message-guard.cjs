const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const ctx={};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync(path.resolve(__dirname,'../message-guard.js'),'utf8'),ctx);
const Guard=ctx.RarRescueMessageGuard;
let callback,interval,cleared=0,clock=1700000000000,answers=[],timeOuts=[];
const timer={schedule:(fn,ms)=>{callback=fn;interval=ms;return 1;},cancel:()=>cleared++,now:()=>clock,onTimeout:e=>timeOuts.push(e)};
const step={kind:'RR_FRAME_CALL',payload:{kind:'RR_SENSOR_NAV_GOTO'}};
const g=new Guard(step,x=>answers.push(x),timer);
assert.equal(interval,90000);
clock+=91000;callback();
assert.equal(answers.length,1);
assert.equal(answers[0].code,'RR_COMMAND_DEADLINE');
assert.equal(answers[0].stage,'RR_FRAME_CALL/RR_SENSOR_NAV_GOTO');
assert.equal(answers[0].elapsedMs,91000);
assert(!g.reply({ok:true}), 'late frame navigation response must not send second result');
assert.equal(answers.length,1);
assert.equal(timeOuts.length,1);
const guard2=new Guard({kind:'RR_HARVEST_PLAN'},x=>answers.push(x),timer);
assert.equal(interval,45000);
assert(guard2.reply({ok:true,processedSourcePaths:['known/file.dat']}));
assert.equal(answers.at(-1).ok,true);
assert.equal(cleared,2);
console.log('PASS: deadline returns once, identifies failed stage, late response blocked, no click replay');
